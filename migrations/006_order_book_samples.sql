-- Order-book snapshots collected from Binance depth streams.
CREATE TABLE IF NOT EXISTS public.order_book_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market TEXT NOT NULL CHECK (market IN ('SPOT', 'USD_M', 'COIN_M')),
    symbol TEXT NOT NULL,
    event_time_ms BIGINT,
    transaction_time_ms BIGINT,
    update_id BIGINT NOT NULL,
    sampled_at TIMESTAMPTZ NOT NULL,
    best_bid DOUBLE PRECISION NOT NULL CHECK (best_bid > 0),
    best_ask DOUBLE PRECISION NOT NULL CHECK (best_ask > best_bid),
    mid_price DOUBLE PRECISION NOT NULL CHECK (mid_price > 0),
    spread_bps DOUBLE PRECISION NOT NULL CHECK (spread_bps >= 0),
    bid_notional DOUBLE PRECISION NOT NULL CHECK (bid_notional >= 0),
    ask_notional DOUBLE PRECISION NOT NULL CHECK (ask_notional >= 0),
    depth_imbalance DOUBLE PRECISION NOT NULL CHECK (depth_imbalance BETWEEN -1 AND 1),
    bids JSONB NOT NULL CHECK (jsonb_typeof(bids) = 'array'),
    asks JSONB NOT NULL CHECK (jsonb_typeof(asks) = 'array'),
    UNIQUE (market, symbol, update_id)
);
CREATE INDEX IF NOT EXISTS idx_order_book_samples_market_symbol_time
    ON public.order_book_samples (market, symbol, event_time_ms DESC, update_id DESC);
