-- Binance USD-M forced liquidation event history.
CREATE TABLE IF NOT EXISTS public.liquidation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time_ms BIGINT NOT NULL CHECK (event_time_ms >= 0),
    trade_time_ms BIGINT NOT NULL CHECK (trade_time_ms >= 0),
    symbol TEXT NOT NULL,
    pair_symbol TEXT,
    market_type INTEGER,
    side TEXT CHECK (side IS NULL OR side IN ('BUY', 'SELL')),
    order_type TEXT,
    status TEXT,
    average_price DOUBLE PRECISION CHECK (average_price IS NULL OR average_price >= 0),
    original_quantity DOUBLE PRECISION CHECK (original_quantity IS NULL OR original_quantity >= 0),
    last_filled_quantity DOUBLE PRECISION CHECK (last_filled_quantity IS NULL OR last_filled_quantity >= 0),
    cumulative_filled_quantity DOUBLE PRECISION CHECK (cumulative_filled_quantity IS NULL OR cumulative_filled_quantity >= 0),
    approx_cumulative_notional DOUBLE PRECISION CHECK (approx_cumulative_notional IS NULL OR approx_cumulative_notional >= 0),
    raw_payload JSONB NOT NULL CHECK (jsonb_typeof(raw_payload) = 'object')
);
CREATE INDEX IF NOT EXISTS idx_liquidation_symbol_time
    ON public.liquidation_events (symbol, event_time_ms DESC, id DESC);
